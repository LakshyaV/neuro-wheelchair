"""Write configs/default.yaml from the settings dataclasses.

Run after changing any default (``make config``). A test compares the file with
the code, so the two cannot drift apart unnoticed.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from nwc import settings

HEADER = """\
# Every setting of neuro-wheelchair with its default value.
#
# Copy the parts you want to change into a file of your own and pass it with
#   nwc <command> -c my-settings.yaml
# or change single values on the command line:
#   nwc <command> -s engine.baseline_s=30
#
# frontend  how samples become analysis frames. A trained model is tied to these values.
# quality   when a frame, or an electrode, is not to be trusted (microvolts).
# protocol  the calibration recording: commands, runs, trials, timing.
# engine    driving: scheme, speeds, supervisor limits. Thresholds left empty (null) come from
#           the trained model, which carries the ones tuned for its wearer.
# sim       the simulator.
#
# This file is generated by tools/write_default_config.py.
"""


def render() -> str:
    return HEADER + "\n" + yaml.safe_dump(settings.defaults(), sort_keys=False, default_flow_style=None, width=100)


def main() -> None:
    path = Path(__file__).resolve().parent.parent / "configs" / "default.yaml"
    path.write_text(render(), encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
